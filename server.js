async function buildActorContext(mood) {
    const actorName = extractActorNameQuery(mood);

    if (!actorName) {
        return null;
    }

    const fallbackActor = fallbackActorByName(actorName);

    const persons = await fetchPersonsByName(actorName);
    const person = persons[0];
    const personId = person?.kinopoiskId || person?.personId || person?.staffId;

    if (!personId) {
        return fallbackActor
            ? {
                actorName: fallbackActor.name,
                personId: `local:${normalizeText(fallbackActor.name)}`,
                actorOnly: isActorOnlyQuery(mood, actorName),
                films: fallbackActor.films
            }
            : null;
    }

    const details = await fetchPersonDetails(personId);
    const rawFilms = Array.isArray(details?.films) ? details.films : [];
    const filmography = uniqueFilms(rawFilms
        .filter((item) => item.filmId && isActingCredit(item))
        .map(normalizePersonFilm))
        .sort((a, b) => actorFilmographyScore(b) - actorFilmographyScore(a))
        .slice(0, MAX_RETURNED_FILMS * 2);

    if (filmography.length === 0) {
        return fallbackActor
            ? {
                actorName: fallbackActor.name,
                personId,
                actorOnly: isActorOnlyQuery(mood, actorName),
                films: fallbackActor.films
            }
            : null;
    }

    // A small enriched head removes TV shows and gets years/posters without flooding Kinopoisk.
    const enrichedHead = await Promise.all(filmography.slice(0, 12).map(async (film) => {
        const detailed = await fetchFilmDetails(film.filmId);
        return detailed
            ? {
                ...film,
                ...detailed,
                actorRole: film.actorRole,
                ratingVoteCount: detailed.ratingVoteCount || film.ratingVoteCount
            }
            : film;
    }));
    const films = rankActorFilmography([
        ...enrichedHead,
        ...filmography.slice(12)
    ]);
    const actorTitle = details?.nameRu || person.nameRu || details?.nameEn || person.nameEn || actorName;

    return {
        actorName: actorTitle,
        personId,
        actorOnly: isActorOnlyQuery(mood, actorName),
        films
    };
}

