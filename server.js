async function resolveCandidateGroups(candidateGroups) {
    const settled = await Promise.allSettled(candidateGroups);

    return settled.flatMap((item) => {
        if (item.status === "fulfilled") {
            return item.value || [];
        }

        logKinopoiskFallback("CANDIDATE GROUP", item.reason);
        return [];
    });
}

function supabaseHeaders(extra = {}) {
    const headers = {
        "apikey": SUPABASE_KEY,
        "Content-Type": "application/json",
        "User-Agent": "CineMoodMovieProxy/1.0",
        ...extra
    };

    // New Supabase sb_secret_/sb_publishable_ keys are opaque API keys, not JWTs.
    // Send Authorization only for legacy JWT keys such as service_role and anon.
    if (!SUPABASE_KEY.startsWith("sb_")) {
        headers.Authorization = `Bearer ${SUPABASE_KEY}`;
    }

    return headers;
}

function supabaseAuthHeaders(extra = {}, forceAuthorization = false) {
    const headers = supabaseHeaders(extra);

    if (forceAuthorization && !headers.Authorization) {
        headers.Authorization = `Bearer ${SUPABASE_KEY}`;
    }

    return headers;
}

async function supabaseAuthRequest(config) {
    const requestConfig = {
        ...config,
        timeout: SUPABASE_TIMEOUT_MS,
        headers: supabaseAuthHeaders(config.headers || {})
    };

    try {
        return await axios(requestConfig);
    } catch (error) {
        if (error.response?.status === 401 && !requestConfig.headers.Authorization) {
            return axios({
                ...requestConfig,
                headers: supabaseAuthHeaders(config.headers || {}, true)
            });
        }

        throw error;
    }
}

