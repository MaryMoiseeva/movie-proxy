function rankActorFilmography(films) {
    const ranked = uniqueFilms(films || [])
        .filter((film) => film.filmId && film.nameRu)
        .sort((left, right) => actorFilmographyScore(right) - actorFilmographyScore(left))
        .slice(0, MAX_RETURNED_FILMS);
    const movieOnly = ranked.filter((film) => !isAnimationFilm(film) && !isSeriesLikeFilm(film));

    return movieOnly.length >= 8
        ? [...movieOnly, ...ranked.filter((film) => !movieOnly.some((item) => item.filmId === film.filmId))].slice(0, MAX_RETURNED_FILMS)
        : ranked;
}

function personNameScore(person, requestedName) {
    const requestedVariants = actorNameVariants(requestedName).map(normalizeText);
    const names = [
        person.nameRu,
        person.nameEn,
        person.nameOriginal
    ].filter(Boolean).map(normalizeText);
    let score = 0;

    for (const name of names) {
        for (const requested of requestedVariants) {
            if (!name || !requested) {
                continue;
            }

            if (name === requested) {
                score += 10;
            } else if (name.includes(requested) || requested.includes(name)) {
                score += 5;
            } else {
                const requestedParts = requested.split(/\s+/).filter(Boolean);
                const matchedParts = requestedParts.filter((part) => name.includes(part)).length;
                score += matchedParts;
            }
        }
    }

    if (looksLikeActorPerson(person)) {
        score += 3;
    }

    return score;
}

