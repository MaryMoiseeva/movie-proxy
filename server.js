function actorFilmographyScore(film) {
    const text = normalizeText([
        film.nameRu,
        film.nameEn,
        film.description,
        ...(film.genres || []).map((item) => item.genre)
    ].filter(Boolean).join(" "));
    const voteCount = Number(film.ratingVoteCount || 0);
    const actorRole = normalizeText(film.actorRole || "");
    let score = ratingValue(film) + Math.min(4.5, Math.log10(Math.max(1, voteCount)) * 0.9);

    if (/драма|триллер|криминал|детектив|фантастика|приключения|боевик|мелодрама/.test(text)) {
        score += 1.2;
    }

    if (/мультфильм|аниме|детский/.test(text)) {
        score -= 1.4;
    }

    if (/сериал|телесериал|ситком|шоу/.test(text)) {
        score -= 2.6;
    }

    if (/\bage\b|\byears?\b|\byoung\b|\bchild\b|\bfriends?\b|\bclassmate\b|в детстве|младш/.test(actorRole)) {
        score -= 4;
    }

    return score;
}

