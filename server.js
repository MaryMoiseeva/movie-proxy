function fallbackRank(films, plan) {
    const targetGenres = new Set(
        (plan.genreIds || []).map((id) => normalizeText(GENRE_NAMES[id]))
    );
    const referenceGenreIds = plan.referenceMovie?.genreIds || [];
    const referenceGenres = new Set(referenceGenreIds.map((id) => normalizeText(GENRE_NAMES[id])));
    const referenceWantsAnimation = referenceGenreIds.some((id) => [18, 24, 33].includes(id));
    const referenceWantsSpace = isSpaceReference(plan);
    const isReferenceMode = Boolean(plan.referenceMovie?.filmId);
    const requiredGenreIds = plan.requiredGenreIds || [];
    const topicKeywords = plan.topicRequiredKeywords || [];
    const exactTopicKeywords = plan.exactTopicKeywords || [];
    const favoriteHints = new Set((plan.favoriteGenreHints || []).map(normalizeText));

    return films
        .map((film) => {
            const filmText = [
                film.nameRu,
                film.nameEn,
                film.description,
                ...(film.genres || []).map((item) => item.genre),
                ...(film.countries || []).map((item) => item.country)
            ].join(" ").toLowerCase();
            const filmGenreIds = genreIdsForFilm(film);
            const requiredOverlap = requiredGenreIds.filter((id) => filmGenreIds.includes(id)).length;
            const topicOverlap = topicKeywords.filter((keyword) => {
                const normalized = normalizeText(keyword);
                return normalized && filmText.includes(normalized);
            }).length;
            const exactTopicOverlap = exactTopicKeywords.filter((keyword) => {
                const normalized = normalizeText(keyword);
                return normalized && filmText.includes(normalized);
            }).length;
            const genreScore = (film.genres || []).reduce((score, item) => {
                return score + (targetGenres.has(normalizeText(item.genre)) ? 2 : 0);
            }, 0);
            const referenceGenreScore = (film.genres || []).reduce((score, item) => {
                return score + (referenceGenres.has(normalizeText(item.genre)) ? 5 : 0);
            }, 0);
            const mediumScore = referenceWantsAnimation
                ? (hasAnyGenreId(film, [18, 24, 33]) ? 12 : -10)
                : 0;
            const spaceScore = referenceWantsSpace
                ? (hasSpaceSignal(film) ? 10 : hasAnyGenreId(film, [6]) ? 3 : -4)
                : 0;
            const explicitSpaceScore = isExplicitSpaceQuery(plan)
                ? (hasSpaceSignal(film) ? 18 : hasAnyGenreId(film, [6]) ? -2 : -18)
                : 0;
            const avoidPenalty = !isReferenceMode && hasAvoidedKeyword(film, plan.avoidKeywords) ? 8 : 0;
            const excludedPenalty = !isReferenceMode && hasExcludedGenre(film, plan.excludeGenreIds) ? 12 : 0;
            const preferenceAvoidPenalty = !isReferenceMode && hasAvoidedKeyword(film, activePreferenceAvoidKeywords(plan)) ? 5 : 0;
            const preferenceGenrePenalty = !isReferenceMode && hasExcludedGenre(film, activePreferenceExcludeGenreIds(plan)) ? 6 : 0;
            const year = Number.parseInt(String(film.year || ""), 10);
            const yearScore = plan.preferredYear && Number.isFinite(year)
                ? Math.max(0, 4 - Math.abs(year - plan.preferredYear))
                : 0;
            const ratingScore = plan.ratingFrom && !plan.hardRating
                ? Math.max(0, ratingValue(film) - plan.ratingFrom)
                : 0;
            const ratingWeight = isReferenceMode ? ratingValue(film) / 4 : ratingValue(film) / 3;
            const collectiveScore = collectiveCompromiseScore(film, plan);
            const favoriteGenreScore = favoriteHints.size > 0
                ? (film.genres || []).reduce((score, item) => score + (favoriteHints.has(normalizeText(item.genre)) ? 0.45 : 0), 0)
                : 0;
            const requiredGenreScore = requiredGenreIds.length > 0
                ? (requiredOverlap * 8) + (requiredOverlap >= 2 ? 8 : 0) - (requiredOverlap === 0 ? 24 : 0)
                : 0;
            const topicScore = topicKeywords.length > 0
                ? (topicOverlap * 16) - (topicOverlap === 0 ? 24 : 0)
                : 0;
            const exactTopicScore = exactTopicKeywords.length > 0
                ? (exactTopicOverlap * 36) - (exactTopicOverlap === 0 ? 60 : 0)
                : 0;
            const lightMismatchPenalty = isDarkGenreRequest(plan)
                && isLightFamilyOrComedy(film)
                && !hasAnyGenreId(film, [17, 1, 5, 12])
                ? 18
                : 0;
            const animationPenalty = !isReferenceMode
                && plan.deprioritizeAnimation
                && hasAnyGenreId(film, [18, 24, 33])
                ? 16
                : 0;

            return {
                film,
                score: genreScore + referenceGenreScore + requiredGenreScore + topicScore + exactTopicScore + mediumScore + spaceScore + explicitSpaceScore + collectiveScore + favoriteGenreScore + ratingWeight + yearScore + ratingScore - avoidPenalty - excludedPenalty - preferenceAvoidPenalty - preferenceGenrePenalty - lightMismatchPenalty - animationPenalty
            };
        })
        .sort((a, b) => b.score - a.score)
        .map((item) => item.film);
}

