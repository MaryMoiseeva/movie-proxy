function actorNameVariants(name) {
    const cleaned = cleanActorName(name);
    const words = cleaned.split(/\s+/).filter(Boolean);
    const deinflected = words.map((word) => {
        if (/^[\p{Script=Cyrillic}-]+$/u.test(word) && word.length > 4) {
            if (word.endsWith("\u0438\u0435\u0439")) return word.slice(0, -3) + "\u0438\u044f";
            if (word.endsWith("\u0435\u0439")) return word.slice(0, -2) + "\u044f";
            if (word.endsWith("\u043e\u0439")) return word.slice(0, -2) + "\u0430";
            if (word.endsWith("\u043e\u043c") || word.endsWith("\u0435\u043c") || word.endsWith("\u044b\u043c") || word.endsWith("\u0438\u043c")) return word.slice(0, -2);
            if (word.endsWith("\u0443") || word.endsWith("\u044e") || word.endsWith("\u0430") || word.endsWith("\u044f")) return word.slice(0, -1);
        }

        return word;
    }).join(" ");

    return [...new Set([
        cleaned,
        deinflected,
        cleaned.replace(/\b\u0451/giu, "\u0435")
    ].map((item) => cleanActorName(item)).filter((item) => item.length >= 3))];
}

function fallbackActorByName(name) {
    const variants = actorNameVariants(name).map(normalizeText);

    return ACTOR_FALLBACK_FILMOGRAPHIES.find((actor) => {
        return actor.aliases.some((alias) => {
            const normalizedAlias = normalizeText(alias);
            return variants.some((variant) => normalizedAlias.includes(variant) || variant.includes(normalizedAlias));
        });
    }) || null;
}

