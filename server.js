function filterHardConstraints(films, plan) {
    return films.filter((film) => {
        const isReferenceMode = Boolean(plan.referenceMovie?.filmId);

        if (plan.referenceMovie?.filmId && Number(film.filmId) === Number(plan.referenceMovie.filmId)) {
            return false;
        }

        const textQuery = normalizeText(plan.originalQuery || "");
        const title = normalizeText(film.nameRu || film.nameEn || "");

        if (!plan.referenceMovie?.filmId && GENERIC_POPULAR_FILM_IDS.has(Number(film.filmId)) && !textQuery.includes(title)) {
            return false;
        }

        if (!isReferenceMode && hasExplicitGenreRequest(plan) && !matchesRequiredGenres(film, plan)) {
            return false;
        }

        if (!isReferenceMode && !matchesExplicitGenres(film, plan)) {
            return false;
        }

        if (!isReferenceMode && isDarkGenreRequest(plan) && isLightFamilyOrComedy(film) && !hasAnyGenreId(film, [17, 1, 5, 12])) {
            return false;
        }

        if (!isReferenceMode && hasExcludedGenre(film, plan.excludeGenreIds)) {
            return false;
        }

        if (!isReferenceMode && plan.blockAnimation && hasAnyGenreId(film, [18, 24, 33])) {
            return false;
        }

        if (!isReferenceMode && hasAvoidedKeyword(film, plan.avoidKeywords)) {
            return false;
        }

        const year = Number.parseInt(String(film.year || ""), 10);

        if (plan.hardYear && plan.yearFrom && (!Number.isFinite(year) || year < plan.yearFrom)) {
            return false;
        }

        if (plan.hardYear && plan.yearTo && (!Number.isFinite(year) || year > plan.yearTo)) {
            return false;
        }

        if (plan.hardRating && plan.ratingFrom && ratingValue(film) < plan.ratingFrom) {
            return false;
        }

        if (plan.hardRating && plan.ratingTo && ratingValue(film) > plan.ratingTo) {
            return false;
        }

        if (plan.hardCountries?.length && !hasRequiredCountry(film, plan.hardCountries)) {
            return false;
        }

        return true;
    });
}

