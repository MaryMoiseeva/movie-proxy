function wait(milliseconds) {
    return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

async function withNetworkRetry(request) {
    try {
        return await request();
    } catch (error) {
        if (!isTransientNetworkError(error)) {
            throw error;
        }

        await wait(350);
        return request();
    }
}

function stableParamsKey(params = {}) {
    return Object.keys(params)
        .sort()
        .map((key) => `${key}=${String(params[key])}`)
        .join("&");
}

function kinopoiskCacheKey(url, params) {
    return `${url}?${stableParamsKey(params)}`;
}

function kinopoiskRetryDelay(error) {
    const retryAfter = Number(error.response?.headers?.["retry-after"]);

    if (Number.isFinite(retryAfter) && retryAfter > 0) {
        return Math.min(retryAfter * 1000, 5000);
    }

    return 1300;
}

async function waitForKinopoiskStartSlot() {
    const gate = kinopoiskStartQueue.then(async () => {
        const now = Date.now();
        const waitMs = Math.max(0, lastKinopoiskStartAt + KINOPOISK_MIN_START_INTERVAL_MS - now);

        if (waitMs > 0) {
            await wait(waitMs);
        }

        lastKinopoiskStartAt = Date.now();
    });

    kinopoiskStartQueue = gate.catch(() => {});
    await gate;
}

async function acquireKinopoiskConcurrencySlot() {
    if (activeKinopoiskRequests < KINOPOISK_MAX_CONCURRENT) {
        activeKinopoiskRequests += 1;
        return;
    }

    await new Promise((resolve) => kinopoiskConcurrencyWaiters.push(resolve));
    activeKinopoiskRequests += 1;
}

function releaseKinopoiskConcurrencySlot() {
    activeKinopoiskRequests = Math.max(0, activeKinopoiskRequests - 1);
    const next = kinopoiskConcurrencyWaiters.shift();

    if (next) {
        next();
    }
}

async function performKinopoiskGet(url, params = {}, attempt = 0) {
    if (!canUseKinopoisk()) {
        throw new Error("Kinopoisk temporarily unavailable");
    }

    await acquireKinopoiskConcurrencySlot();

    try {
        for (let currentAttempt = attempt; ; currentAttempt += 1) {
            await waitForKinopoiskStartSlot();

            if (!canUseKinopoisk()) {
                throw new Error("Kinopoisk temporarily unavailable");
            }

            try {
                return await axios.get(url, {
                    params,
                    headers: {
                        "X-API-KEY": API_KEY
                    },
                    timeout: KINOPOISK_TIMEOUT_MS
                });
            } catch (error) {
                if (error.response?.status === 429) {
                    markKinopoiskBlocked(error, "REQUEST GATE");
                }

                if (error.response?.status === 429 && currentAttempt < 2) {
                    await wait(kinopoiskRetryDelay(error));
                    continue;
                }

                throw error;
            }
        }
    } finally {
        releaseKinopoiskConcurrencySlot();
    }
}

async function kinopoiskGet(url, params = {}) {
    const key = kinopoiskCacheKey(url, params);
    const cached = kinopoiskRequestCache.get(key);

    if (cached && cached.expiresAt > Date.now()) {
        return { data: cached.data };
    }

    if (kinopoiskPendingRequests.has(key)) {
        return kinopoiskPendingRequests.get(key);
    }

    const request = performKinopoiskGet(url, params)
        .then((response) => {
            kinopoiskRequestCache.set(key, {
                data: response.data,
                expiresAt: Date.now() + KINOPOISK_MEMORY_TTL_MS
            });

            return response;
        })
        .finally(() => kinopoiskPendingRequests.delete(key));

    kinopoiskPendingRequests.set(key, request);
    return request;
}

