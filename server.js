function normalizeText(value) {
    return String(value || "")
        .trim()
        .toLowerCase()
        .replace(/^[\s"'.]+|[\s"'.]+$/g, "");
}

function normalizeFilm(item) {
    const rating = item.rating || item.ratingKinopoisk || item.ratingImdb || null;
    const filmId = item.filmId || item.kinopoiskId;

    return {
        filmId,
        nameRu: item.nameRu,
        nameEn: item.nameEn,
        year: item.year ? String(item.year) : "",
        description: item.description || item.shortDescription || "",
        posterUrlPreview: item.posterUrlPreview
            || item.posterUrl
            || (Number(filmId) > 0 ? `https://kinopoiskapiunofficial.tech/images/posters/kp_small/${filmId}.jpg` : FALLBACK_POSTER_URL),
        genres: item.genres || [],
        countries: item.countries || [],
        rating: rating === null || rating === undefined ? null : String(rating),
        duration: item.duration || item.filmLength || item.length || null,
        type: item.type || null,
        ratingVoteCount: item.ratingVoteCount || item.ratingKinopoiskVoteCount || item.ratingImdbVoteCount || 0,
        actorRole: item.actorRole || null
    };
}

function ratingValue(film) {
    const value = Number.parseFloat(String(film.rating || "").replace(",", "."));
    return Number.isFinite(value) ? value : 0;
}

function uniqueFilms(films) {
    const byId = new Map();

    for (const film of films) {
        if (film.filmId && !byId.has(film.filmId)) {
            byId.set(film.filmId, film);
        }
    }

    return Array.from(byId.values());
}

function uniqueReferenceOptions(films) {
    const seen = new Set();

    return (films || []).filter((film) => {
        const titleKey = normalizeText(film.nameRu || film.nameEn || "");
        const yearKey = String(film.year || "");
        const key = titleKey && yearKey
            ? `${titleKey}:${yearKey}`
            : String(film.filmId || "");

        if (!key.trim() || seen.has(key)) {
            return false;
        }

        seen.add(key);
        return true;
    });
}

function normalizeReferenceTitle(value) {
    return normalizeText(value)
        .replace(/[^\p{L}\p{N}]+/gu, " ")
        .replace(/\s+/g, " ")
        .trim();
}

function referenceTitleScore(film, requestedTitle) {
    const wanted = normalizeReferenceTitle(requestedTitle);

    if (!wanted) {
        return 0;
    }

    const titles = [
        film.nameRu,
        film.nameEn
    ]
        .map(normalizeReferenceTitle)
        .filter(Boolean);

    let best = 0;

    for (const title of titles) {
        if (title === wanted) {
            best = Math.max(best, 4);
        } else if (title.startsWith(`${wanted} `)) {
            best = Math.max(best, 3);
        } else if (title.includes(` ${wanted} `)) {
            best = Math.max(best, 1);
        }
    }

    return best;
}

function markKinopoiskBlocked(error, source = "") {
    const status = error.response?.status;
    const isPersonLookup = String(source).startsWith("PERSON ");

    if (status === 402) {
        // The persons endpoint can be unavailable while film search endpoints still work.
        // Do not let one actor lookup move every later recommendation offline.
        if (isPersonLookup) {
            return;
        }

        kinopoiskBlockedUntil = Math.max(kinopoiskBlockedUntil, Date.now() + 10 * 60 * 1000);
    } else if (status === 429) {
        kinopoiskBlockedUntil = Math.max(kinopoiskBlockedUntil, Date.now() + 20 * 1000);
    }
}

function logKinopoiskFallback(source, error) {
    const status = error.response?.status || error.message;
    markKinopoiskBlocked(error, source);
    console.log(`KINOPOISK ${source} FALLBACK:`, status);
}

