function reorderFirstPage(films, plan, pageSize = 10) {
    const unique = uniqueFilms(films);

    if (unique.length <= pageSize) {
        return unique;
    }

    const hasOnlineFilms = unique.some((film) => Number(film.filmId) > 0);
    const allowAnimation = wantsAnimation(plan);
    const queryText = normalizeText(plan.originalQuery || "");
    const front = [];
    const delayed = [];
    const usedRoots = new Set();
    let animationCount = 0;

    for (const film of unique) {
        const root = titleRoot(film);
        const isGenericPopular = GENERIC_POPULAR_FILM_IDS.has(Number(film.filmId))
            && (!root || !queryText.includes(root));
        const isAnimation = isAnimationFilm(film);
        const isLocal = isLocalFallbackFilm(film);
        const rootRepeats = root && usedRoots.has(root);
        const missesExplicitGenre = hasExplicitGenreRequest(plan) && !matchesRequiredGenres(film, plan);
        const missesTopic = (plan.topicRequiredKeywords || []).length > 0 && !matchesTopicKeywords(film, plan);
        const missesExactTopic = (plan.exactTopicKeywords || []).length > 0 && !matchesExactTopicKeywords(film, plan);
        const lightMismatch = isDarkGenreRequest(plan)
            && isLightFamilyOrComedy(film)
            && !hasAnyGenreId(film, [17, 1, 5, 12]);
        const shouldDelay =
            rootRepeats
            || isGenericPopular
            || missesExplicitGenre
            || missesTopic
            || missesExactTopic
            || lightMismatch
            || (hasOnlineFilms && isLocal && front.length < pageSize)
            || (!allowAnimation && isAnimation && animationCount >= 2);

        if (front.length < pageSize && !shouldDelay) {
            front.push(film);

            if (root) {
                usedRoots.add(root);
            }

            if (isAnimation) {
                animationCount += 1;
            }
        } else {
            delayed.push(film);
        }
    }

    const fill = delayed.splice(0, Math.max(0, pageSize - front.length));
    return [...front, ...fill, ...delayed];
}

