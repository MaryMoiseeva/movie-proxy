async function fetchPersonsByName(name) {
    if (!canUseKinopoisk() || !name) {
        return [];
    }

    const variants = actorNameVariants(name);
    const allPersons = [];

    try {
        for (const variant of variants) {
            const response = await kinopoiskGet(
                "https://kinopoiskapiunofficial.tech/api/v1/persons",
                {
                    name: variant,
                    page: 1
                }
            );

            allPersons.push(...(response.data.items || response.data.persons || []));

            if (allPersons.length > 0) {
                break;
            }
        }

        return allPersons
            .filter((person) => person.kinopoiskId || person.personId || person.staffId)
            .filter(looksLikeActorPerson)
            .sort((left, right) => personNameScore(right, name) - personNameScore(left, name));
    } catch (error) {
        logKinopoiskFallback(`PERSON ${name}`, error);
        return [];
    }
}

