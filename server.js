function titleRoot(film) {
    return normalizeText(film.nameRu || film.nameEn || "")
        .split(/[:.?!,(\-]/)[0]
        .replace(/\d+$/, "")
        .trim();
}

function diversifyFilms(films, limit = 15) {
    const usedRoots = new Set();
    const result = [];

    for (const film of films) {
        const root = titleRoot(film);

        if (root && usedRoots.has(root)) {
            continue;
        }

        if (root) {
            usedRoots.add(root);
        }

        result.push(film);

        if (result.length >= limit) {
            break;
        }
    }

    return result;
}

