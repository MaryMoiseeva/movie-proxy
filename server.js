function collectiveCompromiseScore(film, plan) {
    if (!plan.collective) {
        return 0;
    }

    const filmGenreIds = genreIdsForFilm(film);
    const targetGenreIds = new Set(plan.genreIds || []);
    const overlap = filmGenreIds.filter((id) => targetGenreIds.has(id)).length;
    let score = Math.min(6, overlap * 2);

    if (hasAnyGenreId(film, [13, 7, 19, 2, 4])) {
        score += 3;
    }

    if (!targetGenreIds.has(17) && hasAnyGenreId(film, [17])) {
        score -= 8;
    }

    if (hasAvoidedKeyword(film, ["маньяк", "жесток", "война", "трагед"])) {
        score -= 3;
    }

    return score;
}

